"""Install git hooks and the GitHub workflow for the backstop (ADR-0030). Stdlib-only."""

from __future__ import annotations

import stat
import sys
from collections.abc import Sequence
from pathlib import Path

from chatur import __version__
from chatur.backstop import GitError, git

HOOKS = ("pre-commit", "pre-push")
MARKER = "# chatur-managed hook (ADR-0030)"
WORKFLOW_REL = ".github/workflows/chatur.yml"


class InstallError(RuntimeError):
    pass


def _invocation(shared: bool) -> Sequence[str]:
    if shared:
        return ("chatur",)
    return (Path(sys.executable).as_posix(), "-m", "chatur")


def hook_script(name: str, invocation: Sequence[str]) -> str:
    quoted = " ".join(f'"{part}"' for part in invocation)
    return (
        "#!/bin/sh\n"
        f"{MARKER}\n"
        "# Reinstall: chatur git-hooks install   Remove: chatur git-hooks uninstall\n"
        f'exec {quoted} git-hook {name} "$@"\n'
    )


def hooks_dir(root: Path) -> Path:
    """The directory git actually runs hooks from (honours worktrees)."""
    path = Path(git(root, "rev-parse", "--git-path", "hooks").strip())
    return path if path.is_absolute() else root / path


def _custom_hooks_path(root: Path) -> str | None:
    try:
        value = git(root, "config", "--get", "core.hooksPath").strip()
    except GitError:
        return None
    return value or None


def install(root: Path, *, force: bool = False, shared: bool = False) -> list[Path]:
    custom = _custom_hooks_path(root)
    if custom and not force:
        raise InstallError(
            f"core.hooksPath is set ({custom}); another hook manager owns the hooks. Use the "
            "pre-commit framework entries (chatur-pre-commit / chatur-pre-push) or pass --force"
        )
    directory = hooks_dir(root)
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for name in HOOKS:
        path = directory / name
        if path.exists() and MARKER not in path.read_text(encoding="utf-8", errors="replace"):
            if not force:
                raise InstallError(
                    f"{path} exists and isn't managed by Chatur; use --force to replace it"
                )
        path.write_text(hook_script(name, _invocation(shared)), encoding="utf-8", newline="\n")
        path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        written.append(path)
    return written


def uninstall(root: Path) -> list[Path]:
    removed = []
    directory = hooks_dir(root)
    for name in HOOKS:
        path = directory / name
        if path.is_file() and MARKER in path.read_text(encoding="utf-8", errors="replace"):
            path.unlink()
            removed.append(path)
    return removed


def github_workflow(version: str = __version__) -> str:
    return f"""\
# Chatur governance backstop (ADR-0030). Generated by `chatur ci install github`.
name: chatur

on:
  pull_request:
  push:
    branches: [main]

permissions:
  contents: read

jobs:
  chatur:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - uses: nitsharm1910/chatur@v{version}
        with:
          base: ${{{{ github.event.pull_request.base.sha || github.event.before }}}}
          before: ${{{{ github.event.before }}}}
"""


def install_github_workflow(root: Path, *, force: bool = False) -> Path:
    path = root / WORKFLOW_REL
    if path.exists() and not force:
        raise InstallError(f"{path} already exists; use --force to overwrite")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(github_workflow(), encoding="utf-8", newline="\n")
    return path
